# =====================================================================
# 13_table4_headline.R -- format Table 3 (the headline simulation table)
# from the committed canonical maps.
#
#   Rscript R/13_table4_headline.R        (or source() from run_saved.R / run_all.R)
#
# (Formerly 13_table3_headline.R: the table became Table 4 when the paper
# gained a roadmap table, and is Table 3 again since that table was deleted on
# 2026-10-07. The script and output/table4_headline.md keep the number 4 in
# their names so that references stay valid; the heading written below also
# still reads "Table 4".)
#
# Table 3 reports, for the eight prespecified estimators, 95% interval
# coverage and relative SE error (%) in the two primary regimes:
#   S1 -- benign reference regime (low-complexity nuisance library, good overlap)
#   S2 -- a single highly adaptive random-forest nuisance fit
# both at n = 3000, nsim = 2500, delta_cov = 0.02.
#
# No simulation is re-run. The numbers come from output/compass_maps.rds, the
# aggregated cluster output committed to this repository.
#
# The script also CHECKS itself against the values printed in the paper and
# reports any cell that disagrees, so the table cannot drift from the
# manuscript unnoticed.
# =====================================================================

MAP <- "output/compass_maps.rds"
OUT <- "output/table4_headline.md"

stopifnot("canonical map not found" = file.exists(MAP))
m <- readRDS(MAP)

S1_KEY <- "S1_sharp1.0_gb0.025_n3000"
S2_KEY <- "S2_sharp1.0_gb0.025_n3000"
for (k in c(S1_KEY, S2_KEY)) {
  if (is.null(m[[k]])) stop(sprintf("regime '%s' absent from %s", k, MAP))
}

# The eight prespecified estimators, in the paper's row order, with the
# "g fit" column exactly as Table 3 labels it. The map also carries the plug-in
# comparators (GCOMP, CF-GCOMP) and the four additional design cells: the
# mirror cells CV-TMLE-fold, CVQ-TMLE-fold and DC-TMLE-pool (only the last two
# unattested) and SCTMLE. Those belong to the Supplement, not Table 3, and are
# deliberately excluded here.
ROWS <- list(
  list(label = "TMLE",     gfit = "in-sample"),
  list(label = "AIPW",     gfit = "in-sample"),
  list(label = "CVQ-TMLE", gfit = "in-sample ($Q$-only)"),
  list(label = "SS-TMLE",  gfit = "split-half"),
  list(label = "CV-TMLE",  gfit = "cross-fit"),
  list(label = "CF-AIPW",  gfit = "cross-fit"),
  list(label = "DCTMLE",   gfit = "cross-fit"),
  list(label = "DC-AIPW",  gfit = "cross-fit")
)

pick <- function(key, label, col) {
  s <- as.data.frame(m[[key]]$summary)
  i <- which(s$label == label)
  if (length(i) != 1L) stop(sprintf("'%s' matched %d rows in %s", label, length(i), key))
  s[[col]][i]
}

fmt_cov   <- function(x) if (is.na(x)) "--" else sprintf("%.3f", x)
fmt_relse <- function(x) if (is.na(x) || is.nan(x)) "--" else sprintf("%+d", as.integer(round(x)))

tab <- do.call(rbind, lapply(ROWS, function(r) data.frame(
  Implementation = r$label,
  g_fit          = r$gfit,
  S1_cover       = fmt_cov(pick(S1_KEY, r$label, "cover")),
  S1_relSE       = fmt_relse(pick(S1_KEY, r$label, "relSE")),
  S2_cover       = fmt_cov(pick(S2_KEY, r$label, "cover")),
  S2_relSE       = fmt_relse(pick(S2_KEY, r$label, "relSE")),
  stringsAsFactors = FALSE
)))

# ---------------------------------------------------------------------
# Self-check against the values printed in the paper.
# ---------------------------------------------------------------------
PUBLISHED <- data.frame(
  Implementation = c("TMLE", "AIPW", "CVQ-TMLE", "SS-TMLE", "CV-TMLE", "CF-AIPW", "DCTMLE", "DC-AIPW"),
  S1_cover = c("0.928", "0.932", "0.929", "0.918", "0.933", "0.936", "0.935", "0.939"),
  S1_relSE = c("-5", "-4", "-5", "-7", "-3", "-2", "-2", "-2"),
  S2_cover = c("0.384", "0.483", "0.124", "0.999", "0.999", "0.938", "0.993", "0.911"),
  S2_relSE = c("-62", "-52", "-61", "+128", "+125", "+22", "+96", "+9"),
  stringsAsFactors = FALSE
)

norm <- function(x) sub("^\\+", "", x)
mismatch <- character(0)
for (i in seq_len(nrow(tab))) {
  for (col in c("S1_cover", "S1_relSE", "S2_cover", "S2_relSE")) {
    got <- norm(tab[[col]][i]); want <- norm(PUBLISHED[[col]][i])
    if (!identical(got, want)) {
      mismatch <- c(mismatch, sprintf("  %s / %s: regenerated %s, paper prints %s",
                                      tab$Implementation[i], col, got, want))
    }
  }
}

# ---------------------------------------------------------------------
# Write.
# ---------------------------------------------------------------------
md <- c(
  "<!-- AUTO-GENERATED by R/13_table4_headline.R from output/compass_maps.rds -->",
  "",
  "## Table 4 - two primary regimes at n=3000, nsim=2500, delta_cov=0.02",
  "",
  "95% interval coverage and relative SE error (%). S1 is the benign reference regime;",
  "S2 adds a single highly adaptive random-forest nuisance fit. The `g fit` column gives",
  "where the propensity is fit. Coverage MCSE is at most 1 pp. The prespecified",
  "coverage-criterion range is (0.93, 0.97).",
  "",
  "| Implementation | g fit | S1 cover | S1 relSE | S2 cover | S2 relSE |",
  "|---|---|---|---|---|---|",
  apply(tab, 1, function(r) sprintf("| %s | %s | %s | %s | %s | %s |",
                                    r[["Implementation"]], r[["g_fit"]],
                                    r[["S1_cover"]], r[["S1_relSE"]],
                                    r[["S2_cover"]], r[["S2_relSE"]])),
  "",
  sprintf("Source: `%s`, regimes `%s` and `%s`.", MAP, S1_KEY, S2_KEY),
  if (length(mismatch))
    c("", "**WARNING: regenerated cells disagree with the published table:**", "",
      paste0("- ", sub("^  ", "", mismatch)))
  else
    c("", "All 32 cells match the values printed in the paper.")
)
writeLines(md, OUT)

cat("\n")
print(tab, row.names = FALSE)
cat("\n[written]", OUT, "\n")
if (length(mismatch)) {
  cat("*** Table 3 does NOT match the paper (", length(mismatch), " cell(s)):\n", sep = "")
  cat(paste(mismatch, collapse = "\n"), "\n")
  stop("regenerated Table 3 disagrees with the published values")
} else {
  cat("[check] Table 3: all 32 cells match the values printed in the paper\n")
}
